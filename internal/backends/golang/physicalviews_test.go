package golang

import (
	"go/ast"
	"strings"
	"testing"

	"github.com/greatliontech/stipulator/internal/verify"
	"github.com/greatliontech/stipulator/stipulate"
)

// TestPromotedDeclarationSourceKeepsItsSelection prevents a cached source
// lookup from borrowing another view's generated marker.
func TestPromotedDeclarationSourceKeepsItsSelection(t *testing.T) {
	if testing.Short() {
		t.Skip("loads complementary source views through a scoped importer")
	}
	stipulate.Covers(t, "REQ-go-build-selections", "REQ-go-generated-detect")
	neutralAmbient(t)
	dir := writeModule(t, map[string]string{
		"go.mod":           "module example.com/sourceviews\n\ngo 1.27\n",
		"origin/plain.go":  "//go:build !dst\n\npackage origin\ntype T struct{}\nfunc (T) Method() {}\n",
		"origin/marked.go": "//go:build dst\n\n// Code generated by fixture. DO NOT EDIT.\npackage origin\ntype T struct{}\n//line plain.go:20\nfunc (T) Method() {}\n",
		"p/plain.go":       "package p\nimport \"example.com/sourceviews/origin\"\ntype Plain struct { origin.T }\n",
		"p/dst.go":         "//go:build dst\n\npackage p\nimport \"example.com/sourceviews/origin\"\ntype Tagged struct { origin.T }\n",
	})
	dstPolicy(t, dir)
	b, err := newContext(t.Context(), dir, []string{"example.com/sourceviews/p"})
	if err != nil {
		t.Fatal(err)
	}
	for _, row := range []struct {
		name string
		res  verify.Resolution
		file string
	}{
		{"Plain", verify.Resolved, "origin/plain.go"},
		{"Tagged", verify.GeneratedFile, "origin/marked.go"},
	} {
		symbol := "example.com/sourceviews/p." + row.name + ".Method"
		if res, _, err := b.Resolve(symbol); err != nil || res != row.res {
			t.Errorf("%s resolution = %v, %v; want %v", symbol, res, err, row.res)
		}
		if file, ok := b.SymbolFile(symbol); !ok || file != row.file {
			t.Errorf("%s file = %q, %t; want %q", symbol, file, ok, row.file)
		}
	}
	if len(b.sourceLoads) != 2 {
		t.Fatalf("source loads = %d, want two selections", len(b.sourceLoads))
	}
	for key, load := range b.sourceLoads {
		marked := strings.Contains(strings.Join(key.config.BuildFlags, " "), "-tags=dst")
		if len(load.pkg.Syntax) != 1 || ast.IsGenerated(load.pkg.Syntax[0]) != marked {
			t.Fatalf("source cache borrowed another selection's marker: %+v", key)
		}
	}
}
