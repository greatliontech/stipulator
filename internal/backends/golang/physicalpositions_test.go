// TestDeclarationPositionsIgnoreLineDirectives keeps declaration ownership
// and witness classification tied to physical source rather than diagnostic
// filenames chosen by a source directive.
func TestDeclarationPositionsIgnoreLineDirectives(t *testing.T) {
	if testing.Short() {
		t.Skip("loads physical declarations and scoped export-data dependencies")
	}
	stipulate.Covers(t, "REQ-go-build-selections", "REQ-go-generated-detect", "REQ-go-witness-class")
	neutralAmbient(t)
	dir := writeModule(t, map[string]string{
		"go.mod": "module example.com/positions\n\ngo 1.27\n",
		"p/p.go": `package p
import (
 "testing"
 "testing/quick"
 "example.com/positions/generated"
 "example.com/positions/manual"
)
type GeneratedWrapper struct { generated.T }
type ManualWrapper struct { manual.T }
type GenericWrapper struct { generated.Generic[int] }
type InterfaceWrapper interface { manual.I }
type AliasedInterfaceWrapper interface { manual.Alias }
type GeneratedInterfaceWrapper interface { manual.Decoy }
//line imagined_test.go:900
func TestPretend(t *testing.T) { _ = quick.Check(func(int) bool { return true }, nil) }
func FuzzPretend(*testing.F) {}
`,
		"p/p_test.go": `package p
import ("testing"; "testing/quick")
//line imagined.go:700
func TestReal(t *testing.T) {
 _ = quick.Check(func(int) bool { return true }, nil)
}
`,
		"p/aliases_test.go": `package p
import ("testing"; "testing/quick")
type T = testing.T
type F = testing.F
//line elsewhere.go:100
func TestAlias(*T) { _ = quick.Check(func(int) bool { return true }, nil) }
func FuzzAlias(f *F) { f.Add(1); f.Fuzz(func(*T, int) {}) }
func NotATarget(*testing.F) {}
type Helper struct{}
func (Helper) FuzzMethod(*testing.F) {}
`,
		"generated/generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage generated\ntype T struct{}\n//line ordinary.go:20\nfunc (T) Method() {}\ntype Generic[V any] struct{}\nfunc (Generic[V]) GenericMethod(V) {}\n",
		"manual/manual.go":       "package manual\ntype T struct{}\n//line decoy.go:20\nfunc (T) Method() {}\ntype I interface { InterfaceMethod() }\ntype Alias = interface { InterfaceMethod() }\n",
		"manual/decoy.go":        "// Code generated by fixture. DO NOT EDIT.\npackage manual\ntype Decoy = interface { InterfaceMethod() }\n",
	})
	for _, scoped := range []bool{false, true} {
		name, patterns := "whole", []string(nil)
		if scoped {
			name, patterns = "scoped", []string{"example.com/positions/p"}
		}
		t.Run(name, func(t *testing.T) {
			b, err := newContext(t.Context(), dir, patterns)
			if err != nil {
				t.Fatal(err)
			}
			for symbol, file := range map[string]string{
				"TestReal": "p/p_test.go", "TestPretend": "p/p.go",
				"GeneratedWrapper.Method": "generated/generated.go", "ManualWrapper.Method": "manual/manual.go",
				"GenericWrapper.GenericMethod": "generated/generated.go", "InterfaceWrapper.InterfaceMethod": "manual/manual.go",
				"AliasedInterfaceWrapper.InterfaceMethod": "manual/manual.go", "GeneratedInterfaceWrapper.InterfaceMethod": "manual/decoy.go",
			} {
				if got, ok := b.SymbolFile("example.com/positions/p." + symbol); !ok || got != file {
					t.Errorf("%s file = %q, %t; want %q", symbol, got, ok, file)
				}
			}
			for symbol, want := range map[string]verify.Resolution{"GeneratedWrapper.Method": verify.GeneratedFile, "ManualWrapper.Method": verify.Resolved, "GenericWrapper.GenericMethod": verify.GeneratedFile, "InterfaceWrapper.InterfaceMethod": verify.Resolved, "AliasedInterfaceWrapper.InterfaceMethod": verify.Resolved, "GeneratedInterfaceWrapper.InterfaceMethod": verify.GeneratedFile} {
				if got, _, err := b.Resolve("example.com/positions/p." + symbol); err != nil || got != want {
					t.Errorf("%s resolution = %v, %v; want %v", symbol, got, err, want)
				}
			}
			if class, why := b.WitnessClassVerdict("example.com/positions/p.TestReal"); class != verify.PropertyWitness {
				t.Errorf("physical test lost its class: %v, %s", class, why)
			}
			if class, why := b.WitnessClassVerdict("example.com/positions/p.TestPretend"); class != verify.ExampleWitness || !strings.Contains(why, "not a runnable") {
				t.Errorf("production function gained witness class: %v, %s", class, why)
			}
			for _, name := range []string{"TestAlias", "FuzzAlias"} {
				if class, why := b.WitnessClassVerdict("example.com/positions/p." + name); class != verify.PropertyWitness {
					t.Errorf("%s lost its alias-shaped classification: %v, %s", name, class, why)
				}
			}
			for _, name := range []string{"FuzzPretend", "NotATarget", "Helper.FuzzMethod"} {
				if class, why := b.WitnessClassVerdict("example.com/positions/p." + name); class != verify.ExampleWitness || !strings.Contains(why, "not a runnable") {
					t.Errorf("%s gained a non-runnable fuzz classification: %v, %s", name, class, why)
				}
			}
			chain, _, err := b.explainWitness("example.com/positions/p.TestReal")
			if err != nil || chain.Arm != ArmSeedingDirect || len(chain.Links) != 2 {
				t.Errorf("physical witness chain: %+v, %v", chain, err)
			} else if chain.Links[0].Pos != "p/p_test.go:4" || chain.Links[1].Pos != "p/p_test.go:5" {
				t.Errorf("chain positions = %+v; want physical lines 4 and 5", chain.Links)
			}
		})
	}
}

// TestDeclaringSourceFailureRefusesResolution prevents export-data
// diagnostic filenames from becoming the fallback authority when physical
// source recovery fails.
func TestDeclaringSourceFailureRefusesResolution(t *testing.T) {
	if testing.Short() {
		t.Skip("loads an embedded method from export data")
	}
	stipulate.Covers(t, "REQ-go-static-binding", "REQ-go-generated-detect")
	neutralAmbient(t)
	dir := writeModule(t, map[string]string{
		"go.mod":           "module example.com/sourcefault\n\ngo 1.27\n",
		"origin/origin.go": "// Code generated by fixture. DO NOT EDIT.\npackage origin\ntype T struct{}\nfunc (T) Method() {}\n",
		"p/p.go":           "package p\nimport \"example.com/sourcefault/origin\"\ntype T struct { origin.T }\n",
	})
	b, err := newContext(t.Context(), dir, []string{"example.com/sourcefault/p"})
	if err != nil {
		t.Fatal(err)
	}
	for _, selections := range b.lazyCfg {
		for _, cfg := range selections {
			cfg.Dir = t.TempDir()
		}
	}
	const symbol = "example.com/sourcefault/p.T.Method"
	if res, _, err := b.Resolve(symbol); err == nil || res != verify.NotFound || !strings.Contains(err.Error(), "declaring source") {
		t.Fatalf("unreadable declaring source = %v, %v", res, err)
	}
	if file, ok := b.SymbolFile(symbol); ok {
		t.Fatalf("unreadable declaring source acquired a file: %s", file)
	}
	// The source can also move between the importer's export-data load
	// and the declaring-source load. A different signature is not the
	// declaration the importer resolved, even when its name is unchanged.
	b, err = newContext(t.Context(), dir, []string{"example.com/sourcefault/p"})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "origin", "origin.go"), []byte("package origin\ntype T struct{}\nfunc (T) Method(int) {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if res, _, err := b.Resolve(symbol); err == nil || res != verify.NotFound || !strings.Contains(err.Error(), "no longer agrees") {
		t.Fatalf("changed declaring source = %v, %v", res, err)
	}
	if file, ok := b.SymbolFile(symbol); ok {
		t.Fatalf("changed declaring source acquired a file: %s", file)
	}
}
